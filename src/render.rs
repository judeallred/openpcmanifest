fn html(report: &Report) -> String {
    fn rows(out: &mut String, nodes: &[Node]) {
        let leaves: Vec<&Node> = nodes.iter().filter(|n| n.children.is_empty()).collect();
        if !leaves.is_empty() {
            out.push_str("<table>");
            for n in leaves {
                let class = match n.status {
                    Status::Normal => "",
                    other => other.as_str(),
                };
                let _ = write!(
                    out,
                    "<tr><td class=\"k\">{}</td><td class=\"{class}\">{}</td></tr>",
                    html_escape(&n.label),
                    html_escape(n.value.as_deref().unwrap_or(""))
                );
            }
            out.push_str("</table>");
        }
        for n in nodes.iter().filter(|n| !n.children.is_empty()) {
            let value = n
                .value
                .as_ref()
                .map(|v| {
                    format!(
                        " <span class=\"{}\">{}</span>",
                        n.status.as_str(),
                        html_escape(v)
                    )
                })
                .unwrap_or_default();
            let _ = write!(
                out,
                "<details open><summary>{}{value}</summary>",
                html_escape(&n.label)
            );
            rows(out, &n.children);
            out.push_str("</details>");
        }
    }
    let mut out = String::from("<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
    let _ = write!(
        out,
        "<title>PC report \u{2014} {}</title>",
        html_escape(&report.generator)
    );
    let _ = write!(
        out,
        "<style>{HTML_STYLE}</style></head><body><header><h1>PC report</h1>"
    );
    for l in header_lines(report) {
        let _ = write!(out, "<p>{}</p>", html_escape(&l));
    }
    out.push_str("</header><div class=\"wrap\"><nav>");
    for s in &report.sections {
        let _ = write!(out, "<a href=\"#{}\">{}</a>", s.id, html_escape(s.title));
    }
    out.push_str("</nav><main>");
    if !report.notes.is_empty() {
        out.push_str("<div class=\"notes\">");
        for n in &report.notes {
            let _ = write!(out, "<p>{}</p>", html_escape(n));
        }
        out.push_str("</div>");
    }
    for s in &report.sections {
        let _ = write!(
            out,
            "<section id=\"{}\"><h2>{}</h2>",
            s.id,
            html_escape(s.title)
        );
        rows(&mut out, &s.nodes);
        out.push_str("</section>");
    }
    let _ = writeln!(
        out,
        "<footer>Generated by {} \u{b7} <a href=\"{url}\">{url}</a></footer></main></div></body></html>",
        html_escape(&report.generator),
        url = crate::REPOSITORY
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::json;
    use crate::model::{Node, Section};

    fn sample() -> Report {
        let mut summary = Section::new("summary", "Summary");
        summary.push(Node::item("CPU", "AMD Ryzen 5 3600"));
        summary.push(
            Node::group("Storage")
                .with(Node::item("Drive", "4 TB WD"))
                .with(Node::item("Drive", "512 GB Crucial")),
        );
        let mut storage = Section::new("storage", "Storage");
        storage.push(
            Node::group("WDC WD40EZRZ <x>")
                .with(Node::item("Health", "Caution").status(Status::Caution))
                .with(Node::item("Serial", "WD-1").private()),
        );
        Report {
            generator: "OpenPCManifest 0.1.0".into(),
            collected_at: Some("2026-11-15T19:00:00Z".into()),
            sections: vec![summary, storage],
            notes: vec!["Run as administrator for SMART data.".into()],
        }
    }

    #[test]
    fn text_is_indented() {
        let t = render(&sample(), Format::Text);
        assert!(t.contains("Summary\n=======\nCPU: AMD Ryzen 5 3600\nStorage\n  Drive: 4 TB WD\n"));
        assert!(t.contains("Note: Run as administrator"));
    }

    #[test]
    fn markdown_escapes() {
        let m = render(&sample(), Format::Markdown);
        assert!(m.contains("- **WDC WD40EZRZ \\<x\\>**"));
        assert!(m.contains("## Storage"));
    }

    #[test]
    fn html_escapes_and_marks_status() {
        let h = render(&sample(), Format::Html);
        assert!(h.starts_with("<!DOCTYPE html>"));
        assert!(h.contains("WDC WD40EZRZ &lt;x&gt;"));
        assert!(h.contains("<td class=\"caution\">Caution</td>"));
        assert!(!h.contains("<x>"));
    }

    #[test]
    fn json_is_valid_and_complete() {
        let j = render(&sample(), Format::Json);
        let v = json::parse(&j).unwrap();
        assert_eq!(v.get("schemaVersion").as_u64(), Some(1));
        let storage = v.get("sections").items()[1];
        let drive = storage.get("items").items()[0];
        assert_eq!(
            drive.get("children").items()[0].get("status").as_str(),
            Some("caution")
        );
        assert_eq!(
            drive.get("children").items()[1].get("private").as_bool(),
            Some(true)
        );
    }

    #[test]
    fn rig_summary_formats() {
        let md = rig_summary(&sample(), Format::Markdown);
        assert!(md.starts_with("**My PC**"));
        assert!(md.contains("- **Storage:** 4 TB WD; 512 GB Crucial"));
        let bb = rig_summary(&sample(), Format::BbCode);
        assert!(bb.contains("[*][b]CPU:[/b] AMD Ryzen 5 3600"));
        assert!(bb.contains("[/list]"));
    }

    #[test]
    fn bbcode_neutralises_brackets() {
        let mut s = Section::new("x", "X");
        s.push(Node::item("Name", "[url=evil]x[/url]"));
        let r = Report {
            sections: vec![s],
            ..Report::default()
        };
        assert!(render(&r, Format::BbCode).contains("(url=evil)x(/url)"));
    }
}
