//! Renderers: plain text, Markdown, `BBCode`, JSON and a self-contained
//! HTML page. All of them work from the same [`Report`] tree. Callers
//! redact the report first when private values must not be shown.

use std::fmt::Write as _;

use crate::json::Value;
use crate::model::{Node, Report, Section, Status};

/// An output format.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    /// Indented plain text.
    Text,
    /// GitHub-flavoured Markdown.
    Markdown,
    /// Forum `BBCode`.
    BbCode,
    /// JSON.
    Json,
    /// A self-contained HTML page.
    Html,
}

impl Format {
    /// The conventional file extension.
    #[must_use]
    pub const fn extension(self) -> &'static str {
        match self {
            Self::Text => "txt",
            Self::Markdown => "md",
            Self::BbCode => "bbcode.txt",
            Self::Json => "json",
            Self::Html => "html",
        }
    }

    /// A display name.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Text => "Text",
            Self::Markdown => "Markdown",
            Self::BbCode => "BBCode",
            Self::Json => "JSON",
            Self::Html => "HTML",
        }
    }

    /// Every format, in menu order.
    pub const ALL: [Self; 5] = [
        Self::Html,
        Self::Markdown,
        Self::BbCode,
        Self::Text,
        Self::Json,
    ];
}

/// Renders a full report.
#[must_use]
pub fn render(report: &Report, format: Format) -> String {
    match format {
        Format::Text => text(report),
        Format::Markdown => markdown(report),
        Format::BbCode => bbcode(report),
        Format::Json => to_json(report).to_json_pretty(),
        Format::Html => html(report),
    }
}

/// Renders only the Summary section as a short block for forums and chat.
/// Supports Markdown, `BBCode` and text; other formats fall back to text.
#[must_use]
pub fn rig_summary(report: &Report, format: Format) -> String {
    let Some(summary) = report.section("summary") else {
        return String::new();
    };
    let mut out = String::new();
    match format {
        Format::Markdown => {
            out.push_str("**My PC**\n\n");
            for n in &summary.nodes {
                let _ = writeln!(
                    out,
                    "- **{}:** {}",
                    md_escape(&n.label),
                    md_escape(&summary_value(n))
                );
            }
        }
        Format::BbCode => {
            out.push_str("[b]My PC[/b]\n[list]\n");
            for n in &summary.nodes {
                let _ = writeln!(
                    out,
                    "[*][b]{}:[/b] {}",
                    bb_escape(&n.label),
                    bb_escape(&summary_value(n))
                );
            }
            out.push_str("[/list]\n");
        }
        _ => {
            for n in &summary.nodes {
                let _ = writeln!(out, "{}: {}", n.label, summary_value(n));
            }
        }
    }
    let _ = write!(out, "{}", footer(format, &report.generator));
    out
}

fn footer(format: Format, generator: &str) -> String {
    let url = crate::REPOSITORY;
    match format {
        Format::Markdown => format!("\n<sub>Generated by [{generator}]({url})</sub>\n"),
        Format::BbCode => format!("[size=1]Generated by [url={url}]{generator}[/url][/size]\n"),
        _ => format!("\nGenerated by {generator} ({url})\n"),
    }
}

/// A node's value, or its children's values joined, for one-line summaries.
fn summary_value(n: &Node) -> String {
    if let Some(v) = &n.value {
        return v.clone();
    }
    n.children
        .iter()
        .filter_map(|c| c.value.clone())
        .collect::<Vec<_>>()
        .join("; ")
}

fn header_lines(report: &Report) -> Vec<String> {
    let mut lines = vec![report.generator.clone()];
    if let Some(at) = &report.collected_at {
        lines.push(format!("Collected {at}"));
    }
    lines
}

fn text(report: &Report) -> String {
    fn walk(out: &mut String, nodes: &[Node], depth: usize) {
        let pad = "  ".repeat(depth);
        for n in nodes {
            match &n.value {
                Some(v) => {
                    let _ = writeln!(out, "{pad}{}: {v}", n.label);
                }
                None => {
                    let _ = writeln!(out, "{pad}{}", n.label);
                }
            }
            walk(out, &n.children, depth + 1);
        }
    }
    let mut out = String::new();
    for l in header_lines(report) {
        let _ = writeln!(out, "{l}");
    }
    for note in &report.notes {
        let _ = writeln!(out, "Note: {note}");
    }
    for s in &report.sections {
        let _ = writeln!(
            out,
            "\n{}\n{}",
            s.title,
            "=".repeat(s.title.chars().count())
        );
        walk(&mut out, &s.nodes, 0);
    }
    out
}

fn md_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(
            c,
            '\\' | '`' | '*' | '_' | '[' | ']' | '<' | '>' | '|' | '#'
        ) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

fn markdown(report: &Report) -> String {
    fn walk(out: &mut String, nodes: &[Node], depth: usize) {
        let pad = "  ".repeat(depth);
        for n in nodes {
            match &n.value {
                Some(v) => {
                    let _ = writeln!(out, "{pad}- **{}:** {}", md_escape(&n.label), md_escape(v));
                }
                None => {
                    let _ = writeln!(out, "{pad}- **{}**", md_escape(&n.label));
                }
            }
            walk(out, &n.children, depth + 1);
        }
    }
    let mut out = String::from("# PC report\n\n");
    for l in header_lines(report) {
        let _ = writeln!(out, "{}  ", md_escape(&l));
    }
    for note in &report.notes {
        let _ = writeln!(out, "\n> {}", md_escape(note));
    }
    for s in &report.sections {
        let _ = writeln!(out, "\n## {}\n", md_escape(s.title));
        walk(&mut out, &s.nodes, 0);
    }
    out
}

fn bb_escape(s: &str) -> String {
    s.replace('[', "(").replace(']', ")")
}

fn bbcode(report: &Report) -> String {
    fn walk(out: &mut String, nodes: &[Node]) {
        out.push_str("[list]\n");
        for n in nodes {
            match &n.value {
                Some(v) => {
                    let _ = writeln!(out, "[*][b]{}:[/b] {}", bb_escape(&n.label), bb_escape(v));
                }
                None => {
                    let _ = writeln!(out, "[*][b]{}[/b]", bb_escape(&n.label));
                }
            }
            if !n.children.is_empty() {
                walk(out, &n.children);
            }
        }
        out.push_str("[/list]\n");
    }
    let mut out = String::new();
    for s in &report.sections {
        let _ = writeln!(out, "[size=4][b]{}[/b][/size]", bb_escape(s.title));
        walk(&mut out, &s.nodes);
    }
    out.push_str(&footer(Format::BbCode, &report.generator));
    out
}

/// Converts a report to a JSON value. The shape is versioned by
/// `schemaVersion`; see `docs/ARCHITECTURE.md`.
#[must_use]
pub fn to_json(report: &Report) -> Value {
    fn node(n: &Node) -> Value {
        let mut pairs = vec![
            ("key".to_owned(), Value::String(n.key.clone())),
            ("label".to_owned(), Value::String(n.label.clone())),
        ];
        if let Some(v) = &n.value {
            pairs.push(("value".to_owned(), Value::String(v.clone())));
        }
        if n.status != Status::Normal {
            pairs.push((
                "status".to_owned(),
                Value::String(n.status.as_str().to_owned()),
            ));
        }
        if n.private {
            pairs.push(("private".to_owned(), Value::Bool(true)));
        }
        if !n.children.is_empty() {
            pairs.push((
                "children".to_owned(),
                Value::Array(n.children.iter().map(node).collect()),
            ));
        }
        Value::Object(pairs)
    }
    let section = |s: &Section| {
        Value::Object(vec![
            ("id".to_owned(), Value::String(s.id.to_owned())),
            ("title".to_owned(), Value::String(s.title.to_owned())),
            (
                "items".to_owned(),
                Value::Array(s.nodes.iter().map(node).collect()),
            ),
        ])
    };
    Value::Object(vec![
        ("schemaVersion".to_owned(), Value::Number(1.0)),
        (
            "generator".to_owned(),
            Value::String(report.generator.clone()),
        ),
        (
            "collectedAt".to_owned(),
            report
                .collected_at
                .clone()
                .map_or(Value::Null, Value::String),
        ),
        (
            "notes".to_owned(),
            Value::Array(
                report
                    .notes
                    .iter()
                    .map(|n| Value::String(n.clone()))
                    .collect(),
            ),
        ),
        (
            "sections".to_owned(),
            Value::Array(report.sections.iter().map(section).collect()),
        ),
    ])
}

/// Escapes text for HTML element content and attribute values.
#[must_use]
pub fn html_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

